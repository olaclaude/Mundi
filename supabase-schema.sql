-- Ejecutar en el proyecto de Supabase que se vaya a utilizar.
-- La API usa SUPABASE_SERVICE_ROLE_KEY únicamente en el servidor.
create table if not exists public.appointments (
  id bigint generated by default as identity primary key,
  reference text not null unique,
  created_at timestamptz not null default now(),
  status text not null default 'pending',
  service text not null,
  service_label text not null,
  profile text not null,
  details text not null,
  name text not null,
  phone text not null,
  email text,
  contact_preference text not null,
  timeframe text not null,
  slot text not null,
  consent_at timestamptz not null,
  consent_policy text not null
);

create index if not exists appointments_created_at_idx on public.appointments (created_at desc);
create index if not exists appointments_status_idx on public.appointments (status);

alter table public.appointments enable row level security;
revoke all on table public.appointments from anon, authenticated;
-- No se crean políticas para anon/authenticated: las solicitudes solo se leen
-- desde un backend o panel autenticado con credenciales de servidor.
